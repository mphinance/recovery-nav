#!/usr/bin/env python3
"""Independent validation of docs/data/*.json against the raw CSV.

Recomputes everything from the CSV without importing build_data.py, then writes
research/explorer/validation.md. Optional hand-written sections are appended
from explorer/review_notes.md when present.
Usage: .venv/bin/python explorer/validate.py
"""
import csv
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent
CSVP = ROOT / "data" / "raw" / "cleaned_data_all.csv"
DATA = REPO / "docs" / "data"
OUT = REPO / "research" / "explorer" / "validation.md"
Y = ("2022", "2023", "2024", "2025")


def money(s):
    s = (s or "").strip().replace(",", "")
    try:
        return float(s)
    except ValueError:
        return None


def fm(x):
    return "n/a" if x is None else f"${x:,.2f}"


def main():
    rows = list(csv.DictReader(CSVP.open(encoding="utf-8", newline="")))
    counties = json.loads((DATA / "counties.json").read_text())
    items = json.loads((DATA / "items.json").read_text())
    meta = json.loads((DATA / "meta.json").read_text())
    cats = json.loads((DATA / "categories.json").read_text())
    byname = {c["name"]: c for c in counties}
    cmap = {r["gov_name"].strip(): c for r, c in zip(rows, counties)}  # build order == CSV order
    L = ["# Validation report", "", "Generated by explorer/validate.py from the raw CSV and docs/data/*.json.", ""]

    # (d) integrity
    names = [r["gov_name"].strip() for r in rows]
    dup = [n for n, k in Counter(names).items() if k > 1]
    dupids = [n for n, k in Counter(c["id"] for c in counties).items() if k > 1]
    blanks = Counter()
    parse_fail = []
    for r in rows:
        for y in Y:
            for k in ("receipts", "disbursements", "interest"):
                col = f"{y}_{k}"
                if (r[col] or "").strip() == "":
                    blanks[col] += 1
                elif money(r[col]) is None:
                    parse_fail.append((r["gov_name"], col, r[col]))
        for col in ("dec_2025_balance", "percentage spent", "doc_link"):
            if (r[col] or "").strip() == "":
                blanks[col] += 1
            elif col != "doc_link" and money(r[col]) is None:
                parse_fail.append((r["gov_name"], col, r[col]))
    L += ["## (d) Integrity", "",
          f"- Governments in CSV: {len(rows)}; in counties.json: {len(counties)}; counties: {sum(c['type']=='county' for c in counties)}, municipalities: {sum(c['type']=='municipality' for c in counties)}",
          f"- Duplicate names: {dup or 'none'}; duplicate ids: {dupids or 'none'}",
          f"- Blank numeric cells: {dict(blanks) or 'none'}",
          f"- Unparseable numeric cells: {parse_fail or 'none'}",
          f"- Names corrected from source spelling: " + (", ".join(f"{r['gov_name']} -> {cmap[r['gov_name']]['name']}" for r in rows if cmap[r['gov_name']]['name'] != r['gov_name']) or "none"),
          ""]

    # (a) balance check, (b) pct
    L += ["## (a) Balance check: receipts + interest - disbursements vs dec_2025_balance", ""]
    mism, small = [], 0
    tot = dict(r=0.0, d=0.0, i=0.0, b=0.0)
    pct_diffs = []
    for r in rows:
        R = sum(money(r[f"{y}_receipts"]) or 0 for y in Y)
        D = sum(money(r[f"{y}_disbursements"]) or 0 for y in Y)
        I = sum(money(r[f"{y}_interest"]) or 0 for y in Y)
        B = money(r["dec_2025_balance"])
        tot["r"] += R; tot["d"] += D; tot["i"] += I; tot["b"] += B or 0
        delta = round(R + I - D - B, 2)
        chk = money(r["checking math"])
        cj = cmap[r["gov_name"]]
        if abs(cj["receipts_total"] - R) > 0.01 or abs(cj["disbursements_total"] - D) > 0.01 or abs(cj["interest_total"] - I) > 0.01:
            parse_fail.append((r["gov_name"], "json_total_differs_from_recompute", ""))
        if abs(delta) > 0.01:
            if abs(delta) > 1.0:
                mism.append((r["gov_name"], delta, chk, r["notes"].strip(), r["fact_check_notes"].strip()))
            else:
                small += 1
        denom = R + I
        p = D / denom if denom else None
        sp = money(r["percentage spent"])
        if p is not None and sp is not None and abs(p - sp) > 0.0005:
            pct_diffs.append((r["gov_name"], p, sp))
    L.append(f"{len(mism)} governments differ by more than $1.00 (positive delta = reported balance is LOWER than the math implies); {small} differ by $0.01 to $1.00 (rounding). The source's own fact-check rule ignores gaps under $50.")
    L += ["", "| Government | Delta (R+I-D-balance) | Source 'checking math' col | Source note |", "|---|---|---|---|"]
    for n, d, chk, note, fc in sorted(mism, key=lambda t: -abs(t[1])):
        L.append(f"| {n} | {fm(d)} | {fm(chk)} | {(note or fc or '').replace('|','/')[:160]} |")
    L += ["", "Mismatches over $50 are the ones a reader could notice; flagged in counties.json as `balance_mismatch` (threshold $1).", ""]
    # json-level agreement
    bad = [c["id"] for c in counties if ("balance_mismatch" in c["flags"]) != (abs(round(c["receipts_total"] + c["interest_total"] - c["disbursements_total"] - (c["balance_dec_2025"] or 0), 2)) > 1.0)]
    L.append(f"- Flag consistency between counties.json and recompute: {'OK' if not bad else bad}")
    L += ["", "## (b) pct_spent recomputed vs CSV", "",
          f"- Formula: disbursements / (receipts + interest). Governments where recompute differs from the CSV 'percentage spent' by more than 0.0005: {pct_diffs or 'none'}",
          f"- Governments with receipts + interest = 0: {[c['id'] for c in counties if c['pct_spent'] is None] or 'none'}", ""]

    # (c) totals
    tj = meta["totals"]
    L += ["## (c) Statewide totals", "",
          "| Measure | Recomputed from CSV | meta.json | Expected from earlier work |", "|---|---|---|---|",
          f"| Receipts | {fm(tot['r'])} | {fm(tj['receipts'])} | about $162.6M |",
          f"| Disbursements | {fm(tot['d'])} | {fm(tj['disbursements'])} | about $44.06M |",
          f"| Interest | {fm(tot['i'])} | {fm(tj['interest'])} | n/a |",
          f"| Reported Dec 2025 balances (sum) | {fm(tot['b'])} | {fm(tj['balance'])} | about $125.4M unspent |",
          f"| Receipts + interest - disbursements | {fm(tot['r']+tot['i']-tot['d'])} | | |",
          f"| Statewide pct spent (D / (R+I)) | {tot['d']/(tot['r']+tot['i']):.4f} | | |",
          f"| Statewide D / R (excluding interest) | {tot['d']/tot['r']:.4f} | | |", "",
          f"Note: the `balance` total is the sum of REPORTED balances. It differs from receipts + interest - disbursements by " + fm(tot['r']+tot['i']-tot['d']-tot['b']) + ", which is the sum of the per-government deltas in (a). Interest is included in the spendable pot.", ""]

    # (e) coverage
    dollar_total = parsed = 0
    for r in rows:
        for f in ("2025 Expenditures", "2022, 2023, 2024 expenditures"):
            t = r[f]
            dollar_total += len(re.findall(r"\$\s*[\d,]+(?:\.\d+)?|\(\s*\d{1,3}(?:,\d{3})+(?:\.\d+)?\s*\)", t))
    priced = [i for i in items if i["amount"] is not None]
    parsed = len(priced)
    chars_all = sum(len(r[f]) for r in rows for f in ("2025 Expenditures", "2022, 2023, 2024 expenditures"))
    withtext = sum(1 for c in counties if "no_expenditure_text" not in c["flags"])
    L += ["## (e) Item parsing coverage", "",
          f"- Dollar amounts found by a naive scan of all expenditure text: {dollar_total}; items with an amount in items.json: {parsed} ({parsed/dollar_total:.1%})" if dollar_total else "- no dollars found",
          f"- Total items: {len(items)}; priced: {parsed}; unpriced: {len(items)-parsed}",
          f"- Governments with usable expenditure text: {withtext} of {len(counties)}; with at least one priced item: {len({i['county_id'] for i in priced})}",
          f"- Governments with expenditure text and no priced item: {sorted({c['id'] for c in counties if 'no_expenditure_text' not in c['flags']} - {i['county_id'] for i in priced})}",
          f"- Items flagged: " + str(dict(Counter(f for i in items for f in i['flags']))),
          f"- Sum of priced items excluding Milwaukee County (all periods, NOT a spending figure): {fm(sum(i['amount'] for i in priced if i['county_id']!='milwaukee-county'))}",
          f"- Milwaukee County priced items by period (overlapping commitments, never add): " + ", ".join(f"{p}: {fm(sum(i['amount'] for i in priced if i['county_id']=='milwaukee-county' and i['period_label']==p))}" for p in ("2023-2025", "2024-2026")) + f"; Milwaukee County reported disbursements 2022-2025: {fm(byname['Milwaukee County']['disbursements_total'])}",
          ""]
    # unparsed dollars check: amounts in text not in an item
    miss = []
    for r in rows:
        txt = r["2025 Expenditures"] + " " + r["2022, 2023, 2024 expenditures"]
        got = {i["amount"] for i in priced if i["county_id"] == cmap[r["gov_name"]]["id"]}
        for m in re.finditer(r"\$\s*([\d,]+(?:\.\d+)?)|\(\s*(\d{1,3}(?:,\d{3})+(?:\.\d+)?)\s*\)", txt):
            v = float((m.group(1) or m.group(2)).replace(",", ""))
            if v not in got:
                miss.append((r["gov_name"], v))
    L.append(f"- Dollar amounts in text with no matching item amount: {miss or 'none'}")
    L.append("")

    # (f) top 15 per category
    L += ["## (f) Largest 15 priced items per category (for sanity-reading)", ""]
    for c in cats:
        its = sorted((i for i in priced if i["category"] == c["id"]), key=lambda i: -i["amount"])[:15]
        n_all = sum(1 for i in items if i["category"] == c["id"])
        L += [f"### {c['id']} ({n_all} items, {len([i for i in priced if i['category']==c['id']])} priced)", ""]
        for i in its:
            L.append(f"- {fm(i['amount'])} | {i['county_name']} | {i['period_label']} | {i['text'][:110]}")
        L.append("")
    notes = ROOT / "review_notes.md"
    if notes.exists():
        L += ["", notes.read_text()]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}; mismatches>$1: {len(mism)}")


if __name__ == "__main__":
    main()
